export type Locale = "en" | "ar";
export type Theme = "light" | "dark";

interface I18nValue {
  locale: Locale;
  theme: Theme;
  t: (key: MessageKey) => string;
  setLocale: (locale: Locale) => void;
  toggleTheme: () => void;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => (localStorage.getItem("vaultify-locale") === "ar" ? "ar" : "en"));
  const [theme, setTheme] = useState<Theme>(() => {
    const saved = localStorage.getItem("vaultify-theme");
    if (saved === "light" || saved === "dark") return saved;
    return window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
  });

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
    localStorage.setItem("vaultify-locale", locale);
  }, [locale]);

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
    localStorage.setItem("vaultify-theme", theme);
  }, [theme]);

  const value = useMemo<I18nValue>(
    () => ({
      locale,
      theme,
      t: (key) => (locale === "ar" ? ar[key] : en[key]) || key,
      setLocale: setLocaleState,
      toggleTheme: () => setTheme((current) => (current === "dark" ? "light" : "dark")),
    }),
    [locale, theme],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("missing_i18n");
  return value;
}
